// Station catalog. Lane stations: u = metres along the running direction, v = metres across
// (positive = towards the court centre). Items with `f` (0..1) spread with the station length.
// Items describe ONE place. `capacity` (Plätze) repeats them:
//   spots: 'across' (default) -> parallel tracks, `spotStep` metres apart (default 2)
//   spots: 'along'            -> one after another, the station gets capacity x length long
// flow: true -> children follow each other without waiting (no queue warning with 1 place).
// Goal stations: goal-local coordinates, u = metres from the goal line into the court,
// v = across (positive = the side the lane comes from). Plätze is only a number there.
const spread = (type, n, v = 0, extra = {}) =>
  Array.from({ length: n }, (_, i) => ({ type, f: n === 1 ? 0.5 : i / (n - 1), v, ...extra }));
